import { expect, it } from "vitest";

// The invite QR code is our own encoder (public/qr.js). This grid is what the
// segno library makes for the same URL, level M, mask 2, so if the encoder
// breaks, the QR code a client scans would break and this fails.
const { qr } = await import(new URL("../public/qr.js", import.meta.url).href);
const rows = (m: boolean[][]) => m.map((r) => r.map((b) => (b ? 1 : 0)).join(""));

it("makes the same QR code as a reference encoder", () => {
  expect(rows(qr("https://gym.example/join/AbCdEfGhIjKlMnOpQrStUvWx", 2))).toEqual([
    "111111100110100110111111001111111", "100000100110100100100110001000001", "101110101101001110010100001011101",
    "101110101010100100110110001011101", "101110101000101111001011001011101", "100000101010101001010100001000001",
    "111111101010101010101010101111111", "000000001101101010011101100000000", "101111100000111001010010101111100",
    "100100011111110011111101001101100", "111001101101011111001110111010110", "010110001001010001111111001011100",
    "100111110011101110011011010111001", "110101000000100101100110000000011", "111110111101111110101100111001110",
    "110010010100100100000111111011100", "110000111111111101000010110110001", "000000011101110110110101101101101",
    "101001110111111100101010011110110", "101011011010111000001100011111111", "011000110001100100100111010101010",
    "101111001010110111001011011000001", "100011111101010001010110010100010", "100011001101010010111110111011110",
    "101010110111110001110010111110100", "000000001011110011111110100010100", "111111100101010111000011101010110",
    "100000101010001101101111100011101", "101110101001010110010010111111010", "101110101101111101100111110010011",
    "101110101111001111000100011101000", "100000100100011100000101100011100", "111111101011011100010011100100010",
  ]);
});

it("refuses text too long for it rather than making a broken code", () => {
  expect(qr("x".repeat(213)).length).toBe(57);
  expect(() => qr("x".repeat(214))).toThrow();
});
